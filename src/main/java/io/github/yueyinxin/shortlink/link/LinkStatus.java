package io.github.yueyinxin.shortlink.link;

/**
 * 短链状态。
 *
 * <p>只有两个取值，因为「已过期」不作为一个状态存在 —— 它由 {@code expiresAt} 与当前时间
 * 比较得出，是<b>时间流逝的自然结果</b>，而不是一次状态变更。
 *
 * <p>如果把「已过期」也做成状态，就必须有一个定时任务去扫描并翻转状态。这会引入一系列问题：
 * 任务漏跑或延迟时状态与事实不符；任务重启期间时间点丢失；以及"状态是 EXPIRED 但
 * expiresAt 其实在未来"这类不可能自动纠正的不一致数据。
 *
 * <p>而 {@code DISABLED} 必须是一个状态，因为它是<b>人的操作</b>，无法从其他字段推导出来。
 */
public enum LinkStatus {

    /** 启用中，可以跳转（除非已过期）。 */
    ACTIVE,

    /** 已被创建者禁用，拒绝跳转。 */
    DISABLED
}
